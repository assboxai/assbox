"""Render reviewed catalog and dated evidence. No network or runtime capability rules."""
import argparse
from datetime import date
from hashlib import sha256
import json
from pathlib import Path
import re
from component_catalog import read_catalog
from preset_catalog import read_presets

ROOT = Path(__file__).resolve().parent.parent
GENERATED = '<!-- Generated by scripts/product_docs.py; update the reviewed data, then regenerate. -->\n'


def cell(value):
    return str(value).replace('|', '\\|').replace('\n', ' ')


def ids(values):
    return ', '.join('`' + value + '`' for value in values) or 'none'


def catalog_page():
    output = GENERATED + '''# Presets and component catalog

These tables use the same reviewed [preset](../../catalog/presets.json) and
[component](../../catalog/components.json) data as the installer. They describe
initial selections, not installed state or qualification. Individual exclusions
are recorded in generated ordinary Nix settings. Later catalog changes do not
expand an existing machine's selection. Raw module components remain opt-in.

## Guided presets

Tailscale support does not enroll the machine or publish a service. Execution
computer use starts off. The native kiosk is staged until its exact policy gate
passes; its optional protected Code worker is a separate explicit choice.

| Preset | Purpose / revision | Initially checked components | Presentation | Tailscale support | Workload SSH | Web apps |
|---|---|---|---|---|---|---|
'''
    for row in read_presets():
        values = [f'`{row["id"]}`', f'{row["purpose"]} / {row["revision"]}', ids(row['components']),
                  row['presentation'], 'yes' if row['tailscale'] else 'no',
                  'yes' if row['workloadSsh'] else 'no', ids(row['webApps'])]
        output += '| ' + ' | '.join(cell(v) for v in values) + ' |\n'
    output += '''
## Components

Package families are independently held release inputs. Empty command/package
entries represent an integration or service choice, not an extra runtime. Mutable
helper consent and unfree package consent are separate. Placement eligibility
never grants native local-execution authority or proves a transport works.

| ID | Held family | Package / command | Required components | Presentation | Placement | Consent / limitation |
|---|---|---|---|---|---|---|
'''
    for row in read_catalog():
        placement = 'controller' if row['controllerAllowed'] else ('execution / worker' if row['workerAllowed'] else 'standalone')
        consent = (['unfree'] if row['unfree'] else []) + (['mutable helpers'] if row['mutableCode'] else [])
        if row['blocked']:
            consent.append(row['blocked'])
        values = [f'`{row["id"]}`', row['family'], f'{row["package"] or "—"} / {row["command"] or "—"}',
                  ids(row['dependencies']), ', '.join(row['presentations']), placement, '; '.join(consent) or 'none']
        output += '| ' + ' | '.join(cell(v) for v in values) + ' |\n'
    return output + '''
Provider setup, actual transport and integration maturity are described in
[applications](../applications.md) and [Coder routes](coder-options.md).
[Implementation status](../implementation-status.md) distinguishes present
mechanisms from release qualification.
'''


def sources(values, anchors):
    if not values or any(not re.fullmatch(r'S[0-9]{2}', value) or value.lower() not in anchors for value in values):
        raise ValueError('invalid dated evidence source reference')
    return ', '.join(f'[{value}](sources.md#{value.lower()})' for value in values)


CONTROLLER_ROUTE_CASES = {
    'macos-desktop-ssh': ('A099', 'A100', 'A101'),
    'mobile-through-macos-ssh': ('A102',),
    'linux-desktop-worker-ssh': ('A059',),
    'mobile-through-linux-worker': ('A111',),
    'direct-cli-relay': ('A104',),
}
CONTROLLER_ROUTES_START = '<!-- BEGIN REVIEWED CONTROLLER ROUTES -->'
CONTROLLER_ROUTES_END = '<!-- END REVIEWED CONTROLLER ROUTES -->'


def controller_route_status(row, acceptance):
    route = row['id']
    cases = CONTROLLER_ROUTE_CASES[route]
    evidence = row['evidence']
    if evidence is None:
        return 'not run'
    if (not isinstance(evidence, dict) or set(evidence) != {'route', 'source', 'checks'}
            or evidence['route'] != route or not isinstance(evidence['source'], str)
            or not re.fullmatch(r'[a-f0-9]{40}', evidence['source'])
            or not isinstance(evidence['checks'], dict) or set(evidence['checks']) != set(cases)):
        raise ValueError('qualification evidence does not bind the exact controller route')
    for case in cases:
        check = acceptance[case]
        digest = evidence['checks'][case]
        if (not isinstance(digest, str) or not re.fullmatch(r'[a-f0-9]{64}', digest)
                or check['status'] != 'passed'
                or check['evidence'] != {'route': route, 'source': evidence['source'], 'sha256': digest}):
            raise ValueError(f'{route} requires its own reviewed {case} acceptance receipt')
    return 'passed'


def coder_routes_page():
    data = json.loads((ROOT / 'qualification/codex-controller-routes.json').read_text())
    acceptance = {row['id']: row for row in json.loads((ROOT / 'qualification/acceptance.json').read_text())}
    anchors = set(re.findall(r'<a id="([^"]+)"', (ROOT / 'docs/product/sources.md').read_text()))
    reviewed = date.fromisoformat(data['reviewed_local_date'])
    if [row['id'] for row in data['routes']] != list(CONTROLLER_ROUTE_CASES):
        raise ValueError('incomplete or duplicate controller evidence routes')
    if any(case not in acceptance for cases in CONTROLLER_ROUTE_CASES.values() for case in cases):
        raise ValueError('unknown controller route acceptance requirement')
    lines = [
        f'**Upstream evidence reviewed on {reviewed}.** Assbox qualification records an exact route.',
        '',
        '| Route | Upstream evidence | Assbox status | Assbox qualification |',
        '|---|---|---|---|',
    ]
    for row in data['routes']:
        status = controller_route_status(row, acceptance)
        upstream = f'{row["upstream"]} {sources(row["sources"], anchors)}.'
        cases = ', '.join(CONTROLLER_ROUTE_CASES[row['id']])
        qualification = f'{row["qualification"]} {cases}.'
        lines.append('| ' + ' | '.join(map(cell, (row['path'], upstream, status, qualification))) + ' |')
    document = (ROOT / 'docs/product/coder-options.md').read_text()
    if document.count(CONTROLLER_ROUTES_START) != 1 or document.count(CONTROLLER_ROUTES_END) != 1:
        raise ValueError('controller evidence table boundaries are missing or duplicated')
    before, body = document.split(CONTROLLER_ROUTES_START)
    _, after = body.split(CONTROLLER_ROUTES_END)
    return before + CONTROLLER_ROUTES_START + '\n' + '\n'.join(lines) + '\n' + CONTROLLER_ROUTES_END + after


def computer_use_status(row, acceptance, lock_sha256, reviewed):
    state, evidence = row['assbox_status'], row['evidence']
    row_date = date.fromisoformat(row['reviewed_local_date'])
    if row_date > reviewed:
        raise ValueError(f'{row["id"]} review date is newer than the matrix review')
    if state == 'not_run':
        if evidence is not None:
            raise ValueError(f'{row["id"]} unexecuted qualification requires null evidence')
        return 'not run'
    if state not in {'passed', 'partial', 'failed'}:
        raise ValueError(f'{row["id"]} has an invalid Assbox qualification status')
    if (not isinstance(evidence, dict)
            or set(evidence) != {'row', 'product_path', 'source', 'lock_sha256', 'observed_on', 'scope', 'checks'}
            or evidence['row'] != row['id']
            or evidence['product_path'] != row['path']
            or not isinstance(evidence['source'], str)
            or not re.fullmatch(r'[a-f0-9]{40}', evidence['source'])
            or not isinstance(evidence['observed_on'], str)
            or evidence['lock_sha256'] != lock_sha256):
        raise ValueError(f'{row["id"]} requires evidence for this product path and lock')
    if not row_date <= date.fromisoformat(evidence['observed_on']) <= reviewed:
        raise ValueError(f'{row["id"]} evidence is outside the reviewed date range')

    scope = evidence['scope']
    keys = {'architecture', 'surface', 'authentication', 'package_sha256',
            'helper_sha256', 'compiled_features', 'display_backend'}

    def is_digest(value):
        return isinstance(value, str) and re.fullmatch(r'[a-f0-9]{64}', value) is not None

    if (not isinstance(scope, dict) or set(scope) != keys
            or scope['architecture'] not in ('x86_64-linux', 'aarch64-linux')
            or scope['surface'] not in ('browser', 'desktop')
            or not all(isinstance(scope[key], str) and scope[key].strip()
                       for key in ('authentication', 'display_backend'))
            or not is_digest(scope['package_sha256'])
            or not isinstance(scope['helper_sha256'], dict)
            or not all(isinstance(name, str) and name.strip() and is_digest(digest)
                       for name, digest in scope['helper_sha256'].items())
            or not isinstance(scope['compiled_features'], list)
            or not all(isinstance(feature, str) and feature.strip() for feature in scope['compiled_features'])):
        raise ValueError(f'{row["id"]} requires an exact package, helper, authentication and display scope')

    # A114 verifies this matrix. Its own result cannot establish a runtime capability.
    required = set(row['requirements']) - {'A114'}
    checks = evidence['checks']
    if (not isinstance(checks, dict) or not checks or not checks.keys() <= required
            or (state == 'passed' and checks.keys() != required)):
        raise ValueError(f'{row["id"]} requires its own runtime acceptance checks')
    identity = {key: value for key, value in evidence.items() if key != 'checks'}
    for case, digest in checks.items():
        result = acceptance[case]
        stored = result['evidence']
        scoped = stored.get('linux_computer_use') if isinstance(stored, dict) else None
        if (not is_digest(digest) or result['status'] not in {'passed', 'partial', 'failed'}
                or (state == 'passed' and result['status'] != 'passed')
                or not isinstance(scoped, dict)
                or scoped.get(row['id']) != {**identity, 'sha256': digest}):
            raise ValueError(f'{row["id"]} requires a matching reviewed {case} receipt')
    if state == 'failed' and all(acceptance[case]['status'] != 'failed' for case in checks):
        raise ValueError(f'{row["id"]} failed qualification requires a failed runtime check')
    return f'{state} ({scope["surface"]}, {scope["architecture"]}, {scope["display_backend"]})'


def evidence_page():
    data = json.loads((ROOT / 'qualification/linux-computer-use.json').read_text())
    acceptance = {r['id']: r for r in json.loads((ROOT / 'qualification/acceptance.json').read_text())}
    anchors = set(re.findall(r'<a id="([^"]+)"', (ROOT / 'docs/product/sources.md').read_text()))
    reviewed = date.fromisoformat(data['reviewed_local_date'])
    lock_sha256 = sha256((ROOT / 'flake.lock').read_bytes()).hexdigest()
    output = GENERATED + f'# Linux browser and computer-use support\n\n**Reviewed:** {data["reviewed_local_date"]}. **Scope:** {data["scope"]}\n\n'
    output += '''This dated upstream evidence is separate from Assbox qualification. Each row
records its own Assbox status and evidence. The selected application,
authentication mode, package/helper build and display backend require actual
release tests before being advertised as qualified. This table is never loaded
as an installer resolver rule or fetched at boot.

| Product path | Linux browser actions | Linux arbitrary desktop control | Sources | Assbox qualification |
|---|---|---|---|---|
'''
    seen = set()
    for row in data['rows']:
        if row['id'] in seen or not re.fullmatch(r'CU[0-9]{2}', row['id']):
            raise ValueError('invalid dated evidence identifier')
        seen.add(row['id'])
        if not set(row['requirements']) <= acceptance.keys():
            raise ValueError('unknown dated evidence requirement')
        status = computer_use_status(row, acceptance, lock_sha256, reviewed)
        source_links = sources(row['sources'], anchors)
        values = [row['path'], row['browser'], row['desktop'], source_links, status]
        output += '| ' + ' | '.join(cell(v) for v in values) + ' |\n'
    output += '\n## Exact-path qualifications\n\nRequirement IDs identify acceptance work in the [release ledger](../../qualification/acceptance.json). Upstream evidence cannot silently promote a row to an Assbox pass.\n'
    for row in data['rows']:
        evidence = cell(json.dumps(row['evidence'], sort_keys=True)) if row['evidence'] else 'no evidence'
        output += f'\n### {row["id"]} — {row["path"]}\n\n**Reviewed:** {row["reviewed_local_date"]}. **Assbox status:** {row["assbox_status"].replace("_", " ")}; {evidence}.\n\n'
        output += f'**Scope and limits:** {row["scope"]}\n\n**Implementation requirement:** {row["implementation"]}\n\n**Qualification references:** {", ".join(row["requirements"])}.\n\n**Upstream evidence:** {sources(row["sources"], anchors)}.\n'
    return output + '''
## How to use this evidence

A limitation of a native consumer application is not a limitation of the same
model used through another Linux-capable harness. An API or alternative harness
needs its own tools, authentication and qualification.

Browser automation is not arbitrary desktop control. A virtual display is an
execution resource and does not isolate same-UID agents. Installing Xvfb cannot
enable an unsupported native feature. Current upstream documentation and
otherwise compiled binaries do not override evidence about the selected closure.

Update the reviewed JSON when qualifying a release, retaining source date,
package revision, compiled features and test record. Missing or stale evidence
is neither a pass nor proof that a route cannot work. Stable environment and
authority rules are in [computer-use policy](computer-use.md). The
[source register](sources.md) preserves provider claims and dates.
'''


def outputs():
    return {
        ROOT / 'docs/product/component-presets.md': catalog_page(),
        ROOT / 'docs/product/linux-computer-use-support.md': evidence_page(),
        ROOT / 'docs/product/coder-options.md': coder_routes_page(),
    }


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, text in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f'generated product documentation drift: {path.relative_to(ROOT)}')
        else:
            path.write_text(text)
