"""Compile reviewed preset data into pure Rust values. No runtime recipes."""
import argparse,json,subprocess
from pathlib import Path
from component_catalog import read_catalog,variant
ROOT=Path(__file__).resolve().parent.parent
OUTPUT=ROOT/'crates/functional-core/assbox-domain/src/preset_ids.rs'
def generate():
 catalog={r['id']:r for r in read_catalog()}
 rows=json.loads((ROOT/'catalog/presets.json').read_text())
 assert [r['id'] for r in rows]==sorted({r['id'] for r in rows})
 s='// SPDX-License-Identifier: GPL-3.0-or-later\n// Generated by scripts/preset_catalog.py.\nuse crate::{Component, Presentation};\nuse crate::instances::{Preset, Purpose};\npub const PRESETS: &[Preset] = &[\n'
 for r in rows:
  assert set(r)=={'id','purpose','revision','components','presentation','tailscale','workloadSsh','webApps'}
  assert r['purpose'] in ['assistant','coder','kiosk','custom'] and r['revision']>=1
  assert set(r['components'])<=catalog.keys() and len(r['components'])==len(set(r['components']))
  assert all(set(catalog[c]['dependencies'])<=set(r['components']) for c in r['components'])
  assert set(r['webApps'])<={'chatgpt','claude'}
  cs=', '.join('Component::'+variant(c) for c in r['components'])
  s+=f'Preset {{ id: {json.dumps(r["id"])}, purpose: Purpose::{variant(r["purpose"])}, revision: {r["revision"]}, components: &[{cs}], presentation: Presentation::{variant(r["presentation"])}, tailscale: {str(r["tailscale"]).lower()}, workload_ssh: {str(r["workloadSsh"]).lower()}, web_apps: &['+', '.join(json.dumps(a) for a in r['webApps'])+'] },\n'
 s+='];\n'
 return subprocess.run(['rustfmt','--edition','2024'],input=s,text=True,capture_output=True,check=True).stdout
if __name__=='__main__':
 a=argparse.ArgumentParser();a.add_argument('--check',action='store_true');args=a.parse_args();text=generate()
 if args.check:
  if not OUTPUT.exists() or OUTPUT.read_text()!=text:raise SystemExit('preset metadata drift: run scripts/preset_catalog.py')
 else:OUTPUT.write_text(text)
